/**
 * ДЕМО-МОДЕЛЬ линии фронта: грубое кейфрейм-приближение реальных фаз
 * (вторжение → отход с севера → Харьковское контрнаступление → Херсон →
 * Бахмут → Авдеевка → медленные изменения 2024–2025).
 *
 * НЕ является точной картой. В продакшене этот модуль заменяется
 * импортёром DeepState/ISW (см. docs/03 §5). Известные упрощения демо:
 *  - Крым и Донбасс на 24.02.2022 соединены тонкой прибрежной полосой
 *    (реально сухопутный коридор замкнулся в марте 2022);
 *  - Курская операция 2024 не моделируется (модель отслеживает только
 *    контроль территории Украины).
 *
 * Модель региона: полилиния фронта (кейфреймы) + фиксированная линия
 * «границы» на оккупированной стороне; кольцо полигона замыкается
 * автоматически по ближайшим вершинам границы (docs/06 §7).
 */
import type { LngLat } from "@uwt/geo";

export interface RegionKeyframe {
  date: string;
  /** Полилиния фронта: юг-регион — с севера на юг, север-регион — с запада на восток. */
  front: LngLat[];
}

export interface Region {
  id: string;
  /** Дни существования зоны (вне диапазона полигон отсутствует). */
  activeFrom: string;
  activeTo: string | null;
  /** Периметр на оккупированной стороне (госграница/побережье), фиксированный. */
  border: LngLat[];
  keyframes: RegionKeyframe[];
}

